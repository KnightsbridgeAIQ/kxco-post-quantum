#!/usr/bin/env node
// Copy the noble files the FIPS module needs into src/fips/vendor/.
//
// The module boundary has to be a fixed set of files, so the module cannot
// resolve noble through node_modules, where an install, an override or a
// hoisting change could put different bytes behind the same name. Instead the
// files are copied from the exact versions pinned in package.json, and only
// their import specifiers are rewritten, from '@noble/<pkg>/<file>' to a
// relative path inside vendor/. Nothing else in a file changes.
//
//   node scripts/vendor-fips.mjs           write src/fips/vendor/
//   node scripts/vendor-fips.mjs --check   exit 1 if src/fips/vendor/ differs
//
// A noble update is therefore: bump the pin, run this script, commit. CI runs
// --check, so a vendor directory that has drifted from the pins fails the build.

import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, join, relative, resolve, sep, posix } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const MODULES = join(ROOT, 'node_modules')
const VENDOR = join(ROOT, 'src', 'fips', 'vendor')
const PACKAGES = ['@noble/post-quantum', '@noble/hashes', '@noble/curves']
const ENTRIES = [
  '@noble/post-quantum/ml-kem.js',
  '@noble/post-quantum/ml-dsa.js',
  '@noble/hashes/sha2.js',
  '@noble/hashes/hmac.js',
]
// An import or re-export statement starting in column 0, as noble's compiled
// files write them. It may span lines but never crosses a quote or a `;`, so it
// cannot run on from an earlier statement into an example inside a comment.
const SPECIFIER = /^((?:import|export)\b[^'";]*?\bfrom\s*['"])([^'"]+)(['"])/gm

const check = process.argv.includes('--check')

function sourcePath(spec, from) {
  if (spec.startsWith('.')) return resolve(dirname(from), spec)
  const [scope, name, ...rest] = spec.split('/')
  return join(MODULES, scope, name, ...rest)
}

// Destination of a node_modules file inside vendor/, e.g. vendor/hashes/sha2.js.
function vendorPath(file) {
  const rel = relative(MODULES, file).split(sep)
  return join(VENDOR, rel[1], ...rel.slice(2))
}

function closure() {
  const seen = new Set()
  const todo = ENTRIES.map((e) => sourcePath(e, ''))
  while (todo.length) {
    const file = todo.pop()
    if (seen.has(file)) continue
    seen.add(file)
    const src = readFileSync(file, 'utf8')
    for (const m of src.matchAll(SPECIFIER)) todo.push(sourcePath(m[2], file))
  }
  return [...seen].sort()
}

function rewrite(file) {
  const out = vendorPath(file)
  return readFileSync(file, 'utf8').replace(SPECIFIER, (_, head, spec, tail) => {
    const target = vendorPath(sourcePath(spec, file))
    let rel = relative(dirname(out), target).split(sep).join(posix.sep)
    if (!rel.startsWith('.')) rel = './' + rel
    return head + rel + tail
  })
}

function build() {
  const files = new Map()
  const versions = {}
  for (const pkg of PACKAGES) {
    const meta = JSON.parse(readFileSync(join(MODULES, pkg, 'package.json'), 'utf8'))
    versions[pkg] = meta.version
    files.set(join(VENDOR, pkg.split('/')[1], 'LICENSE'), readFileSync(join(MODULES, pkg, 'LICENSE'), 'utf8'))
  }
  const sources = {}
  for (const file of closure()) {
    const out = vendorPath(file)
    files.set(out, rewrite(file))
    sources[relative(VENDOR, out).split(sep).join('/')] =
      createHash('sha256').update(readFileSync(file)).digest('hex')
  }
  const record = {
    note: 'Generated by scripts/vendor-fips.mjs. Do not edit. sha256 is of the upstream file before its import specifiers were rewritten.',
    versions,
    sources,
  }
  files.set(join(VENDOR, 'VENDOR.json'), JSON.stringify(record, null, 2) + '\n')
  return files
}

function existing(dir) {
  const out = new Map()
  let entries
  try { entries = readdirSync(dir, { withFileTypes: true }) } catch { return out }
  for (const entry of entries) {
    const p = join(dir, entry.name)
    if (entry.isDirectory()) for (const [k, v] of existing(p)) out.set(k, v)
    else out.set(p, readFileSync(p, 'utf8'))
  }
  return out
}

const want = build()
if (check) {
  const have = existing(VENDOR)
  const problems = []
  for (const [p, body] of want) if (have.get(p) !== body) problems.push(`differs or missing: ${relative(ROOT, p)}`)
  for (const p of have.keys()) if (!want.has(p)) problems.push(`not produced by the pinned versions: ${relative(ROOT, p)}`)
  if (problems.length) {
    console.error('src/fips/vendor/ does not match the pinned noble versions; run node scripts/vendor-fips.mjs')
    for (const p of problems) console.error('  ' + p)
    process.exit(1)
  }
  console.log(`src/fips/vendor/ matches the pinned noble versions (${want.size} files)`)
} else {
  rmSync(VENDOR, { recursive: true, force: true })
  for (const [p, body] of want) {
    mkdirSync(dirname(p), { recursive: true })
    writeFileSync(p, body)
  }
  console.log(`wrote ${want.size} files to ${relative(ROOT, VENDOR)}`)
}
